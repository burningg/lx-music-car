const assert = require('node:assert/strict')
const { createHash } = require('node:crypto')
const { mkdtemp, writeFile, rm, readFile } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const path = require('node:path')
const { test } = require('node:test')
const { matches } = require('./prepare-offline-stt.cjs')
const { targets } = require('./build-offline-stt.cjs')
const manifest = require('./offline-stt-assets.json')
const root = path.resolve(__dirname, '..')
const read = file => readFile(path.join(root, file), 'utf8')

test('WeType package contains only pinned XNet and UTF-8 vocabulary, not Zipformer/runtime/cloud binaries', () => {
  assert.equal(manifest.engine, 'wetype')
  assert.match(manifest.upstreamRevision, /^[a-f0-9]{40}$/)
  assert.equal(manifest.files.length, 2)
  assert.deepEqual(manifest.files.map(file => path.basename(file.path)).sort(), ['dict.decoder.utf8.txt', 'model.xnet'])
  assert.equal(manifest.files.reduce((n, file) => n + file.size, 0), 135776202)
  for (const file of [manifest.package, ...manifest.files, ...manifest.testFiles]) {
    assert.match(file.sha256, /^[a-f0-9]{64}$/)
    assert.ok(file.size > 0)
    if (file.url) assert.equal(new URL(file.url).protocol, 'https:')
  }
  assert.ok(manifest.testFiles.every(file => file.path.startsWith('test-assets/')))
  assert.ok(manifest.files.every(file => !/\.(wav|so|onnx|aar)$/.test(file.path)))
})

test('asset validation detects missing, truncated and same-size corrupt files', async() => {
  const dir = await mkdtemp(path.join(tmpdir(), 'lx-stt-test-'))
  const file = path.join(dir, 'asset')
  const data = Buffer.from('known-model')
  const artifact = { size: data.length, sha256: createHash('sha256').update(data).digest('hex') }
  try {
    assert.equal(await matches(file, artifact), false)
    await writeFile(file, data)
    assert.equal(await matches(file, artifact), true)
    await writeFile(file, data.subarray(1))
    assert.equal(await matches(file, artifact), false)
    await writeFile(file, Buffer.alloc(data.length))
    assert.equal(await matches(file, artifact), false)
  } finally { await rm(dir, { recursive: true, force: true }) }
})

test('Android uses bounded local PCM/JNI and cancellation; model metadata matches the download lock', async() => {
  const native = await read('android/app/src/main/java/cn/toside/music/car/speech/SpeechRecognitionModule.kt')
  const engine = await read('android/app/src/main/java/cn/toside/music/car/speech/WetypeEngine.kt')
  const gradle = await read('android/app/build.gradle')
  const proguard = await read('android/app/proguard-rules.pro')
  assert.match(native, /AudioRecord\(/)
  assert.match(native, /VOICE_RECOGNITION/)
  assert.match(native, /newSingleThreadExecutor/)
  assert.match(native, /engine\?\.release\(\)/)
  assert.match(native, /session\.engine\?\.cancel\(\)/)
  assert.match(native, /emitState\(session, "processing"\)/)
  assert.doesNotMatch(native, /android\.speech|RecognizerIntent|https?:\/\/|OnlineStream|Zipformer/)
  assert.match(engine, /noBackupFilesDir/)
  assert.match(engine, /MessageDigest.getInstance\("SHA-256"\)/)
  assert.match(engine, /MAX_SAMPLES = SAMPLE_RATE \* 20/)
  assert.match(engine, /!endpoint.heardSpeech/)
  for (const file of manifest.files) {
    assert.ok(engine.includes(file.sha256))
    assert.ok(engine.includes(String(file.size)))
  }
  assert.match(gradle, /\.stt\/wetype/)
  assert.match(gradle, /build-offline-stt.cjs/)
  assert.match(gradle, /main.jniLibs.srcDir/)
  assert.doesNotMatch(gradle, /sherpa|onnxruntime|sherpa-onnx-jni/)
  assert.match(proguard, /-keep class cn\.toside\.music\.car\.speech\.WetypeNative/)
})

test('native runtime is offline-only, two-threaded, cancellable and detects optional ARM64 dot-product instructions', async() => {
  const cargo = await read('android/offline-stt/Cargo.toml')
  const model = await read('android/offline-stt/vendor/wtlocal/model.rs')
  const kernels = await read('android/offline-stt/vendor/wtlocal/kernels.rs')
  const bridge = await read('android/offline-stt/src/bridge.rs')
  const build = await read('scripts/build-offline-stt.cjs')
  assert.doesNotMatch(cargo, /voicekey-core|reqwest|tokio|sherpa|onnx/)
  assert.match(model, /\.min\(2\)/)
  assert.match(model, /cancelled.load\(Ordering::Relaxed\)/)
  assert.match(kernels, /is_aarch64_feature_detected!\("dotprod"\)/)
  assert.match(kernels, /target_feature\(enable = "dotprod"\)/)
  assert.match(bridge, /catch_unwind/)
  assert.match(bridge, /Arc<Session>/)
  assert.match(build, /--locked/)
  assert.match(build, /21-clang/)
  assert.match(build, /max-page-size=16384/)
  assert.deepEqual(Object.keys(targets).sort(), ['arm64-v8a', 'armeabi-v7a', 'x86', 'x86_64'])
})
