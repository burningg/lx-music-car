const assert = require('node:assert/strict')
const { createHash } = require('node:crypto')
const { mkdtemp, writeFile, rm, readFile } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const path = require('node:path')
const { test } = require('node:test')
const { matches } = require('./prepare-offline-stt.cjs')
const manifest = require('./offline-stt-assets.json')
const root = path.resolve(__dirname, '..')

test('offline package contains just the official mixed-quantization graphs, tokens and pinned engine/runtime sources', () => {
  assert.equal(manifest.files.filter(file => file.path.startsWith('assets/')).length, 4)
  assert.ok(manifest.files.every(file => !file.path.endsWith('.aar')))
  const models = manifest.files.filter(file => file.path.endsWith('.onnx'))
  assert.equal(models.length, 3)
  assert.equal(models.filter(file => file.path.endsWith('.int8.onnx')).length, 2)
  assert.ok(models.some(file => file.path.endsWith('/decoder-epoch-99-avg-1.onnx')))
  assert.ok(models.reduce((total, file) => total + file.size, 0) < 58 * 1048576)
  for (const file of [...manifest.files, ...manifest.testFiles]) {
    assert.match(file.sha256, /^[a-f0-9]{64}$/)
    assert.ok(file.size > 0)
    assert.equal(new URL(file.url).protocol, 'https:')
    if (file.url.includes('huggingface.co')) assert.ok(file.url.includes(`/resolve/${manifest.modelRevision}/`))
  }
  assert.ok(manifest.testFiles.every(file => file.path.startsWith('test-assets/')))
  assert.ok(manifest.files.every(file => !file.path.endsWith('.wav')))
})

test('asset validation detects missing, truncated and same-size corrupt files', async() => {
  const dir = await mkdtemp(path.join(tmpdir(), 'lx-stt-test-'))
  const file = path.join(dir, 'asset')
  const data = Buffer.from('known-model')
  const artifact = { size: data.length, sha256: createHash('sha256').update(data).digest('hex') }
  try {
    assert.equal(await matches(file, artifact), false)
    await writeFile(file, data)
    assert.equal(await matches(file, artifact), true)
    await writeFile(file, data.subarray(1))
    assert.equal(await matches(file, artifact), false)
    await writeFile(file, Buffer.alloc(data.length))
    assert.equal(await matches(file, artifact), false)
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('Android uses AudioRecord and bundled CPU graphs, never a system or network recognizer', async() => {
  const native = await readFile(path.join(root, 'android/app/src/main/java/cn/toside/music/car/speech/SpeechRecognitionModule.kt'), 'utf8')
  const engine = await readFile(path.join(root, 'android/app/src/main/java/cn/toside/music/car/speech/ZipformerEngine.kt'), 'utf8')
  const gradle = await readFile(path.join(root, 'android/app/build.gradle'), 'utf8')
  const proguard = await readFile(path.join(root, 'android/app/proguard-rules.pro'), 'utf8')
  assert.match(native, /AudioRecord\(/)
  assert.match(native, /VOICE_RECOGNITION/)
  assert.match(native, /newSingleThreadExecutor/)
  assert.match(native, /stream\?\.release\(\)/)
  assert.match(native, /engine\?\.release\(\)/)
  assert.doesNotMatch(native, /android\.speech|RecognizerIntent|https?:\/\//)
  assert.match(engine, /provider = "cpu"/)
  assert.match(engine, /assetManager = assets/)
  assert.match(engine, /inputFinished\(\)/)
  assert.match(gradle, /noCompress \+= \["onnx"\]/)
  assert.doesNotMatch(gradle, /implementation files.*\.aar/)
  const cmake = await readFile(path.join(root, 'android/app/src/main/cpp/CMakeLists.txt'), 'utf8')
  assert.match(cmake, /SHERPA_ONNX_ENABLE_TTS OFF/)
  assert.match(cmake, /SHERPA_ONNX_ENABLE_SPEAKER_DIARIZATION OFF/)
  assert.match(cmake, /SHERPA_ONNX_ENABLE_JNI ON/)
  assert.match(gradle, /abiFilters\(\*reactNativeArchitectures\(\)\)/)
  assert.match(proguard, /-keep class com\.k2fsa\.sherpa\.onnx\.\*\*/)
})
